// Replicate_state must leave batch-only entries (memory, memory_lengths,
// projected_memory) in place when the base Decoder expands the beam.
TEST(RNNTest, RNNDecoderReplicateStateHonorsBatchOnlyEntries) {
  // Build a minimal RNNDecoder whose weights are irrelevant for this test;
  // we only exercise the replicate_state policy on the decoder instance.
  using namespace rnn_fixtures;
  RNNMockModel model;
  // Decoder scope
  model.register_variable("decoder/embeddings/weight",
                          StorageView({V, E_dec}, std::vector<float>(V * E_dec, 0.0f)));
  // Init state Dense+LN project E_mem -> H
  model.register_variable("decoder/init_state/linear/weight",
                          StorageView({H, E_mem}, std::vector<float>(H * E_mem, 0.0f)));
  model.register_variable("decoder/init_state/linear/bias",
                          StorageView({H}, std::vector<float>(H, 0.0f)));
  model.register_variable("decoder/init_state/layer_norm/gamma",
                          StorageView({H}, std::vector<float>(H, 1.0f)));
  model.register_variable("decoder/init_state/layer_norm/beta",
                          StorageView({H}, std::vector<float>(H, 0.0f)));
  register_gru_cell(model, "decoder/cell/gru1", E_dec, H,
                    cgru_gru1_W_in, cgru_gru1_b_in, cgru_gru1_W_rec,
                    cgru_gru1_g_in, cgru_gru1_g_rec);
  register_gru_cell(model, "decoder/cell/gru2", E_mem, H,
                    cgru_gru2_W_in, cgru_gru2_b_in, cgru_gru2_W_rec,
                    cgru_gru2_g_in, cgru_gru2_g_rec);
  register_bahdanau(model, "decoder/cell/attention", A, H, E_mem,
                    cgru_Wq, cgru_Wm, cgru_v, cgru_g_state, cgru_g_ctx, cgru_b_ctx);
  model.register_variable("decoder/hidden/linear/weight",
                          StorageView({H, H + E_mem + E_dec}, std::vector<float>(H * (H + E_mem + E_dec), 0.0f)));
  model.register_variable("decoder/hidden/linear/bias",
                          StorageView({H}, std::vector<float>(H, 0.0f)));
  model.register_variable("decoder/hidden/layer_norm/gamma",
                          StorageView({H}, std::vector<float>(H, 1.0f)));
  model.register_variable("decoder/hidden/layer_norm/beta",
                          StorageView({H}, std::vector<float>(H, 0.0f)));
  model.register_variable("decoder/output/weight",
                          StorageView({V, H}, std::vector<float>(V * H, 0.0f)));
  model.register_variable("decoder/output/bias",
                          StorageView({V}, std::vector<float>(V, 0.0f)));
  model.finalize();

  layers::RNNDecoder decoder(model, "decoder");

  EXPECT_FALSE(decoder.replicate_state("memory"));
  EXPECT_FALSE(decoder.replicate_state("memory_lengths"));
  EXPECT_FALSE(decoder.replicate_state("projected_memory"));
  // The hidden state (per-beam) must be replicated.
  EXPECT_TRUE(decoder.replicate_state("hidden"));

  // Build a state with memory + memory_lengths and request a beam replication:
  // memory tensors should keep their original batch dim.
  layers::DecoderState state = decoder.initial_state();
  state["memory"] = StorageView({B, S, E_mem}, expected_encoder_output);
  state["memory_lengths"] = StorageView({B}, lengths);

  decoder.replicate_state(state, /*beam_size=*/3);
  ASSERT_EQ(state.at("memory").dim(0), B);
  ASSERT_EQ(state.at("memory_lengths").dim(0), B);
  // "hidden" was empty at this point so it stays empty after replication.
  EXPECT_TRUE(state.at("hidden").empty());
}


