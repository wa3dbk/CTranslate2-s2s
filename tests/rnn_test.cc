// Register one Marian GRU cell's weights under the given scope.
void register_gru_cell(RNNMockModel& model, const std::string& scope,
                       dim_t in_dim, dim_t h_dim,
                       const std::vector<float>& W_in,
                       const std::vector<float>& b_in,
                       const std::vector<float>& W_rec,
                       const std::vector<float>& g_in,
                       const std::vector<float>& g_rec) {
  model.register_variable(scope + "/input/weight",
                          StorageView({3 * h_dim, in_dim}, W_in));
  model.register_variable(scope + "/input/bias",
                          StorageView({3 * h_dim}, b_in));
  model.register_variable(scope + "/recurrent/weight",
                          StorageView({3 * h_dim, h_dim}, W_rec));
  model.register_variable(scope + "/recurrent/bias",
                          StorageView({3 * h_dim}, std::vector<float>(3 * h_dim, 0.0f)));
  model.register_variable(scope + "/ln_input/gamma",
                          StorageView({3 * h_dim}, g_in));
  model.register_variable(scope + "/ln_input/beta",
                          StorageView({3 * h_dim}, std::vector<float>(3 * h_dim, 0.0f)));
  model.register_variable(scope + "/ln_recurrent/gamma",
                          StorageView({3 * h_dim}, g_rec));
  model.register_variable(scope + "/ln_recurrent/beta",
                          StorageView({3 * h_dim}, std::vector<float>(3 * h_dim, 0.0f)));
}

